// Writes src/app/core/build-info.ts with the package version, the build time and the short commit.
// Runs before start, check and build so the app can show which release is installed.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
let commit = '';
try { commit = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* not a git checkout */ }
const body = `// Generated by scripts/build-info.mjs. Do not edit or commit.
export const BUILD_INFO = { version: ${JSON.stringify(version)}, builtAt: ${JSON.stringify(new Date().toISOString())}, commit: ${JSON.stringify(commit)} } as const;
`;
writeFileSync(new URL('../src/app/core/build-info.ts', import.meta.url), body);
